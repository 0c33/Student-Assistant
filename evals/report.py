"""Turn the eval CSVs into the README's tables, so no number is ever typed by hand.

    uv run evals/report.py                 # print the report and rewrite README.md between the eval markers
    uv run evals/report.py --no-readme     # print only

Reads evals/results/{A,B}.csv (from evals/run.py), plus two hand-made files when present:
- root_causes.csv  config,task,trial,root_cause,note   one row per failed trial, labelled from its transcript with
                                                        the course's labels (wrong fact, missing tool call, unsafe
                                                        action, refused wrongly, language, grader too strict, model error)
- judge_check.csv   config,task,trial,human,judge,note   answers graded by hand before reading the judge's verdict
"""

from __future__ import annotations

import argparse
import csv
import json
import sys
from collections import Counter, defaultdict
from pathlib import Path

EVALS = Path(__file__).resolve().parent
RESULTS = EVALS / "results"
README = EVALS.parent / "README.md"
START, END = "<!-- eval:start (generated by evals/report.py) -->", "<!-- eval:end -->"
CAUSES = ["wrong fact", "missing tool call", "unsafe action", "refused wrongly", "language", "grader too strict",
          "model error"]


def load(path: Path) -> list[dict]:
    if not path.is_file():
        return []
    with path.open(encoding="utf-8") as f:
        return list(csv.DictReader(f))


def report(results: Path = RESULTS) -> str:
    runs = {name: load(results / f"{name}.csv") for name in ("A", "B")}
    runs = {k: v for k, v in runs.items() if v}
    if not runs:
        return "_No eval results yet: run `uv run evals/run.py --config A B --trials 3`._"
    meta = json.loads((results / "meta.json").read_text(encoding="utf-8")) if (results / "meta.json").is_file() else {}
    passed = lambda r: r["passed"] == "True"  # noqa: E731
    k = max(int(r["trial"]) for rows in runs.values() for r in rows) + 1
    out = [f"Model `{meta.get('model', '?')}` (judge: `{meta.get('small_model', '?')}`), recorded "
           f"{meta.get('recorded', '?')}, today pinned to {meta.get('today', '?')}, {k} trials per task per config. "
           f"Reproduce offline: `uv run evals/run.py --config A B --trials {k} --replay`.", ""]

    out += ["| Config | Memory | Trials | Pass rate | pass@k | pass^k (k = %d) | Avg requests | Avg tokens |" % k,
            "|---|---|---:|---:|---:|---:|---:|---:|"]
    labels = {"A": "read with `read_file` (spec instruction)", "B": "injected in the system prompt"}
    per_task: dict[str, dict[str, list[bool]]] = {}
    for name, rows in runs.items():
        tasks: dict[str, list[bool]] = defaultdict(list)
        for r in rows:
            tasks[r["task"]].append(passed(r))
        per_task[name] = tasks
        n = len(rows)
        out.append(f"| {name} | {labels.get(name, '')} | {n} | {sum(map(passed, rows)) / n:.2f} | "
                   f"{sum(any(v) for v in tasks.values()) / len(tasks):.2f} | "
                   f"{sum(all(v) for v in tasks.values()) / len(tasks):.2f} | "
                   f"{sum(int(r['steps']) for r in rows) / n:.1f} | {sum(int(r['tokens']) for r in rows) / n:,.0f} |")

    categories = sorted({r["category"] for rows in runs.values() for r in rows})
    out += ["", "| Category | " + " | ".join(f"{c} passed" for c in runs) + " |", "|---|" + "---:|" * len(runs)]
    for cat in categories:
        cells = []
        for rows in runs.values():
            sub = [r for r in rows if r["category"] == cat]
            cells.append(f"{sum(map(passed, sub))}/{len(sub)}")
        out.append(f"| {cat} | " + " | ".join(cells) + " |")

    if len(runs) == 2:
        out += ["", "**What flipped between A and B** (trials passed out of %d; tasks with the same result left out):" % k,
                "", "| Task | A | B | Direction |", "|---|---:|---:|---|"]
        flips = 0
        for task in sorted(per_task["A"]):
            a, b = sum(per_task["A"][task]), sum(per_task["B"].get(task, []))
            if a != b:
                flips += 1
                out.append(f"| `{task}` | {a}/{k} | {b}/{k} | {'B better' if b > a else 'A better'} |")
        if not flips:
            out.append("| (none) | | | |")

    failures = [(name, r) for name, rows in runs.items() for r in rows if not passed(r)]
    labelled = {(r["config"], r["task"], r["trial"]): r for r in load(results / "root_causes.csv")}
    out += ["", "**Error analysis** (every failed trial, labelled from its transcript in "
            "`evals/results/transcripts/`):", "", "| Root cause | Count (A) | Count (B) | Example task | Fix tried |",
            "|---|---:|---:|---|---|"]
    counts: dict[str, Counter] = defaultdict(Counter)
    examples: dict[str, str] = {}
    fixes: dict[str, str] = {}
    for name, r in failures:
        lab = labelled.get((name, r["task"], r["trial"]))
        cause = lab["root_cause"] if lab else "unlabelled"
        counts[cause][name] += 1
        examples.setdefault(cause, f"`{r['task']}`")
        if lab and lab.get("fix"):
            fixes.setdefault(cause, lab["fix"])
    for cause in [c for c in CAUSES if c in counts] + [c for c in counts if c not in CAUSES]:
        out.append(f"| {cause} | {counts[cause]['A']} | {counts[cause]['B']} | {examples[cause]} | "
                   f"{fixes.get(cause, '')} |")
    if not failures:
        out.append("| (no failures) | 0 | 0 | | |")

    checks = load(results / "judge_check.csv")
    if checks:
        agree = sum(c["human"] == c["judge"] for c in checks)
        out += ["", f"**Judge check:** {len(checks)} judged answers graded by hand before reading the verdict; "
                    f"the judge agreed on {agree}/{len(checks)} (`evals/results/judge_check.csv`)."]
    return "\n".join(out)


def update_readme(text: str) -> bool:
    readme = README.read_text(encoding="utf-8")
    if START not in readme or END not in readme:
        return False
    before, rest = readme.split(START, 1)
    after = rest.split(END, 1)[1]
    README.write_text(f"{before}{START}\n{text}\n{END}{after}", encoding="utf-8")
    return True


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--no-readme", action="store_true")
    ap.add_argument("--results", type=Path, default=RESULTS)
    args = ap.parse_args()
    text = report(args.results)
    print(text)
    (args.results / "report.md").write_text(text + "\n", encoding="utf-8") if args.results.is_dir() else None
    if not args.no_readme:
        print("\nREADME.md updated." if update_readme(text) else "\nREADME.md has no eval markers: not updated.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
